#!/usr/bin/env python3
"""Miami Browser installer template from Tauri's NSIS template (tauri-bundler, MIT / Apache-2.0).

Miami Browser is the same program as Chihua: the same uninstall key, install folder, executable, data folder and
AppUserModelID (all keep ${PRODUCTNAME} = "Chihua"). Only what people see changes: the installer title, the
"Apps" list entry, Start menu and desktop shortcuts (name and icon). Those use ${DISPLAYNAME} = "Miami Browser".

    python3 patch_template.py installer.tauri-<version>.nsi installer.nsi

Run it again with the new upstream file when the Tauri CLI is upgraded; it fails if a line it patches moved.
"""
import re
import sys

SRC, DST = sys.argv[1], sys.argv[2]
text = open(SRC, encoding='utf-8').read()


def sub(pattern, repl, count=1):
    global text
    new, n = re.subn(pattern, repl, text)
    if n < count:
        sys.exit(f'patch_template: "{pattern}" matched {n} times, expected {count}')
    text = new


sub(r'(!define PRODUCTNAME "\{\{product_name\}\}"\n)',
    r'\1; Miami Browser: visible name and shortcut icon (keys, folders and the exe stay Chihua)\n'
    r'!define DISPLAYNAME "Miami Browser"\n!define DISPLAYICON "$INSTDIR\\miami.ico"\n')
sub(r'\nName "\$\{PRODUCTNAME\}"', '\nName "${DISPLAYNAME}"')
sub(r'VIAddVersionKey "ProductName" "\$\{PRODUCTNAME\}"', 'VIAddVersionKey "ProductName" "${DISPLAYNAME}"')
sub(r'VIAddVersionKey "FileDescription" "\$\{PRODUCTNAME\}"', 'VIAddVersionKey "FileDescription" "${DISPLAYNAME}"')
sub(r'CheckIfAppIsRunning "\$\{MAINBINARYNAME\}\.exe" "\$\{PRODUCTNAME\}"', 'CheckIfAppIsRunning "${MAINBINARYNAME}.exe" "${DISPLAYNAME}"', 2)
sub(r'"Open with \$\{PRODUCTNAME\}"', '"Open with ${DISPLAYNAME}"')
sub(r'"DisplayName" "\$\{PRODUCTNAME\}"', '"DisplayName" "${DISPLAYNAME}"')
sub(r'"DisplayIcon" "\$\\"\$INSTDIR\\\$\{MAINBINARYNAME\}\.exe\$\\""', '"DisplayIcon" "$\\"${DISPLAYICON}$\\""')
# every shortcut: name Miami Browser.lnk
sub(r'\$\{PRODUCTNAME\}\.lnk', '${DISPLAYNAME}.lnk', 10)
# new shortcuts get the Miami icon
sub(r'(CreateShortcut "[^"]+\.lnk" "\$INSTDIR\\\$\{MAINBINARYNAME\}\.exe")\n', r'\1 "" "${DISPLAYICON}" 0\n', 3)

header = ('; GENERATED by patch_template.py from ' + SRC.rsplit('/', 1)[-1] + ' (Tauri NSIS template, MIT / Apache-2.0).\n'
          '; Miami Browser = Chihua with its own visible name and icon. Do not edit by hand.\n')
open(DST, 'w', encoding='utf-8').write(header + text)
print('written', DST)
